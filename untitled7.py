"""Introducing threshold"""

import numpy as np
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    precision_score,
    recall_score,
    f1_score
)

# Split the existing training partition into fit and validation sets
X_fit, X_val, y_fit, y_val = train_test_split(
    X_train,
    y_train,
    test_size=0.20,
    random_state=42,
    stratify=y_train
)

# Fit preprocessing and classifier using inner training data only
validation_model = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", LogisticRegression(
        class_weight="balanced",
        max_iter=2000,
        random_state=42
    ))
])

validation_model.fit(X_fit, y_fit)

# Validation probabilities
val_prob = validation_model.predict_proba(X_val)[:, 1]

# Compare operating thresholds
results = []

for threshold in np.arange(0.10, 0.91, 0.05):
    val_pred = (val_prob >= threshold).astype(int)

    results.append({
        "Threshold": round(threshold, 2),
        "Precision": precision_score(
            y_val, val_pred, zero_division=0
        ),
        "Recall": recall_score(
            y_val, val_pred, zero_division=0
        ),
        "F1": f1_score(
            y_val, val_pred, zero_division=0
        ),
        "Predicted_Alerts": int(val_pred.sum()),
        "Missed_Failures": int(
            ((y_val == 1) & (val_pred == 0)).sum()
        )
    })

threshold_results = pd.DataFrame(results)

print(
    threshold_results.round(3).to_string(index=False)
)

